export const getProductById = (id: string): Product | undefined => {
  return PRODUCTS.find(p => p.id === id || p.slug === id);
};

export const getProductsByCategory = (categoryId: string): Product[] => {
  if (!categoryId || categoryId === 'all') return PRODUCTS;
  return PRODUCTS.filter(p => p.category === categoryId);
};

export const getProductsByMember = (memberId: string): Product[] => {
  if (!memberId || memberId === 'all') return PRODUCTS;
  return PRODUCTS.filter(p => p.members.includes(memberId as MemberId));
};

export const getNewArrivals = (limit: number = 13): Product[] => {
  return PRODUCTS.filter(p => p.isNew).slice(0, limit);
};

export const getBestSellers = (limit: number = 13): Product[] => {
  return PRODUCTS.filter(p => p.isBestSeller).slice(0, limit);
};

export const getDiscountedProducts = (): Product[] => {
  return PRODUCTS.filter(p => !!p.discount && p.discount > 0);
};
